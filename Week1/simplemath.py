a = 2 + 2
print("Addition:", a)

# exponentiation operator
b = 5 ** 3
print("Power:", b)

# remainder operator
c = 14 % 4
print("Remainder:", c)

# division operator
d = 25 / 4
print("Division:", d)

# Integer division operator
e = 25 // 4
print("Integer division:", e)

# multiplication operator
f = 6 * 3
print("Multiplication:", f)

# addition operator
g = 7 + 5
print("Addition2:", g)

# subtraction operator
h = 9 - 1
print("Subtraction:", h)

print("Whole value:", a + b + c + d + e + f + g + h)

# Order of operations
i = 2 ** 4 % (6 * 2) + (1 // 4) - (2 / 4)
print("Order of operations:", i)

# Order of operations with brackets
j = ((4 - 1) + (7 - 2) - (1 - 3)) * 2
print("Order of operations with brackets:", j)
